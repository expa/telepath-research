import { makeRing, driveOf, step, responses, decode, PHASES } from "./organics.ts";
const s = makeRing();
const target = Math.PI / 2;
const drive = driveOf([target]);
const run = (phase, secs, d = drive) => { s.target = { ...PHASES[phase] }; for (let i = 0; i < secs * 1000; i++) step(s, d, 0.001); };
const none = driveOf([]);
run("present", 0.3);
run("hold", 0.2, none);
const held = decode(responses(s));
console.assert(Math.abs(held.angle - target) < 0.2, "stores the target", held);
run("hold", 2, none);
const later = decode(responses(s));
console.assert(Math.abs(later.strength - held.strength) / held.strength < 0.05, "sustained: memory holds for 2 s", held, later);
run("shift", 0.5, none);
const moved = decode(responses(s));
console.assert(moved.angle - target > 0.3, "derivative weights move it", moved);
run("clear", 0.3, none);
console.assert(decode(responses(s)).strength < 0.05 * held.strength, "clears");
console.log("organics ok", held.strength.toFixed(2), (moved.angle * 180 / Math.PI).toFixed(0));
